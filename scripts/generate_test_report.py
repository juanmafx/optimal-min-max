# Runs the test suite and writes a sanitized JUnit report and Markdown summary to reports/tests/.
import json
import os
import platform
import subprocess
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "reports" / "tests"


def main() -> int:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as scratch:
        junit_path = Path(scratch) / "junit.xml"
        coverage_path = Path(scratch) / "coverage.json"
        command = [
            sys.executable,
            "-m",
            "pytest",
            f"--junitxml={junit_path}",
            "--cov=py_low_hig",
            f"--cov-report=json:{coverage_path}",
            "--cov-report=term",
        ]
        environment = {**os.environ, "COVERAGE_FILE": str(Path(scratch) / ".coverage")}
        exit_code = subprocess.run(command, cwd=ROOT, env=environment, check=False).returncode
        tree = ElementTree.parse(junit_path)
        suite = tree.getroot().find("testsuite")
        if suite is None:
            raise RuntimeError("JUnit report has no test suite")
        suite.attrib.pop("hostname", None)
        tree.write(OUTPUT / "junit.xml", encoding="utf-8", xml_declaration=True)
        totals = json.loads(coverage_path.read_text(encoding="utf-8"))["totals"]
    tests = int(suite.attrib["tests"])
    failures = int(suite.attrib["failures"])
    errors = int(suite.attrib["errors"])
    skipped = int(suite.attrib["skipped"])
    lines = [
        "# Test Report",
        "",
        "Generated by `scripts/generate_test_report.py` from an actual local run.",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Generated at (UTC) | {datetime.now(UTC).strftime('%Y-%m-%d %H:%M:%S')} |",
        f"| Python | {platform.python_version()} |",
        f"| Platform | {platform.system()} {platform.machine()} |",
        f"| Tests | {tests} |",
        f"| Passed | {tests - failures - errors - skipped} |",
        f"| Failed | {failures} |",
        f"| Errors | {errors} |",
        f"| Skipped | {skipped} |",
        f"| Line and branch coverage of `src/py_low_hig` | {totals['percent_covered']:.2f}% |",
        f"| Pytest exit code | {exit_code} |",
        "",
    ]
    (OUTPUT / "summary.md").write_text("\n".join(lines), encoding="utf-8")
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
